/** Locale- and numeral-aware formatting. Never hand-roll date strings. */
export function formatDateTime(d: Date, locale: Locale, numerals: 'latn' | 'arab' = 'latn') {
  return new Intl.DateTimeFormat(`${locale}-u-nu-${numerals}`, {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(d);
}
